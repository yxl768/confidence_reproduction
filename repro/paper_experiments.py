"""Run and score the real DockGen experiments from the official processed data.

Planning is read-only. GPU work requires --execute and a complete preflight.
No hypothetical report figures are read or generated by this module.
"""

import argparse
import csv
import json
import pickle
import re
import shlex
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OFFICIAL = ROOT / "official"
DEFAULT_RUNS = ROOT / "runs" / "paper"
SEEDS = (101, 202)


def dependencies():
    try:
        import numpy as np
    except ImportError as exc:
        raise RuntimeError("This command needs NumPy; use the GPU environment or install numpy locally.") from exc
    return np


def paths(official):
    data = official / "data" / "BindingMOAD_2020_processed"
    return {
        "data": data,
        "full_names": data / "test_names.npy",
        "cluster_names": data / "test_names_bootstrapping.npy",
        "cluster_map": data / "new_cluster_to_ligands.pkl",
        "split_map": official / "data" / "splits" / "MOAD_generalisation_splits.pkl",
        "moad_esm": data / "moad_sequences_new.pt",
        "sequences": official / "data" / "sequences_to_id.fasta",
        "score": official / "workdir" / "pretrained_score",
        "confidence": official / "workdir" / "pretrained_confidence",
    }


def dataset_manifest(official, strict=True):
    np = dependencies()
    p = paths(official)
    required = ["full_names", "cluster_names", "cluster_map", "split_map", "moad_esm", "sequences"]
    missing = [str(p[k]) for k in required if not p[k].is_file()]
    for model, ckpt in (("score", "best_ema_inference_epoch_model.pt"),
                        ("confidence", "best_model.pt")):
        for name in ("model_parameters.yml", ckpt):
            if not (p[model] / name).is_file():
                missing.append(str(p[model] / name))
    for directory in ("pdb_protein", "pdb_ligand"):
        if not (p["data"] / directory).is_dir():
            missing.append(str(p["data"] / directory))
    if missing:
        if strict:
            raise RuntimeError("Required processed inputs are missing:\n" + "\n".join(missing))
        return None, missing

    def read_names(path):
        values = [str(v) for v in np.load(path, allow_pickle=False).tolist()]
        if len(values) != len(set(values)):
            raise ValueError("Duplicate complex names in " + str(path))
        return values

    full = read_names(p["full_names"])
    subset = read_names(p["cluster_names"])
    if len(full) != 189 or len(subset) != 85 or not set(subset) <= set(full):
        raise ValueError("Expected 189 full and 85 cluster complexes, with cluster names a subset of full.")
    # These pickle files are supplied by the official dataset, not by arbitrary users.
    with p["cluster_map"].open("rb") as handle:
        cluster_map = pickle.load(handle)
    groups = {}
    for cluster, ligands in cluster_map.items():
        selected = sorted(set(ligands) & set(subset))
        if selected:
            groups[str(cluster)] = selected
    assigned = [name for names in groups.values() for name in names]
    if len(groups) != 8 or sorted(assigned) != sorted(subset):
        raise ValueError("Official 85-name list must map uniquely to exactly eight clusters.")
    with p["split_map"].open("rb") as handle:
        splits = pickle.load(handle)
    if not set(groups) <= set(splits["test"]):
        raise ValueError("Some selected clusters are absent from the official test split.")
    return {"full": full, "subset": subset, "groups": dict(sorted(groups.items()))}, []


def choose_clusters(manifest, cluster):
    names = list(manifest["groups"])
    if cluster == "all":
        return names
    if cluster.isdigit():
        index = int(cluster)
        if not 1 <= index <= len(names):
            raise ValueError("Cluster index must be 1 through 8.")
        return [names[index - 1]]
    if cluster not in manifest["groups"]:
        raise ValueError("Unknown cluster: " + cluster)
    return [cluster]


def slug(cluster):
    safe = re.sub(r"[^a-z0-9]+", "-", cluster.lower()).strip("-")[:52]
    return safe or "cluster"


def evaluation_seed(training_seed, repeat):
    return training_seed * 1000 + repeat


def name_files(manifest, runs_dir):
    np = dependencies()
    directory = runs_dir / "manifests"
    directory.mkdir(parents=True, exist_ok=True)
    np.save(directory / "full189.npy", np.asarray(manifest["full"]))
    np.save(directory / "clusters85.npy", np.asarray(manifest["subset"]))
    result = {}
    for index, (cluster, names) in enumerate(manifest["groups"].items(), 1):
        file = directory / f"cluster{index:02d}_{slug(cluster)}.npy"
        np.save(file, np.asarray(names))
        result[cluster] = file
    (directory / "manifest.json").write_text(
        json.dumps({"source": "official processed DockGen", "full_count": 189,
                    "subset_count": 85, "clusters": manifest["groups"]}, ensure_ascii=False, indent=2),
        encoding="utf-8")
    return result


def inference_command(official, model_dir, checkpoint, names_path, out_dir, seed, embeddings, sequences, samples):
    p = paths(official)
    return [sys.executable, "-m", "inference", "--dataset", "moad", "--split", "test",
            "--data_dir", str(p["data"]), "--model_dir", str(model_dir), "--ckpt", checkpoint,
            "--filtering_model_dir", str(p["confidence"]), "--filtering_ckpt", "best_model.pt",
            "--esm_embeddings_path", str(embeddings),
            "--moad_esm_embeddings_sequences_path", str(sequences),
            "--names_path", str(names_path), "--out_dir", str(out_dir),
            "--cache_path", str(out_dir.parents[1] / "cache"),
            "--limit_complexes", "0", "--samples_per_complex", str(samples),
            "--inference_steps", "20", "--batch_size", "4", "--seed", str(seed)]


def training_command(official, cluster, run_name, seed, args):
    p = paths(official)
    command = [sys.executable, "-m", "finetune_train", "--run_name", run_name,
               "--log_dir", str(args.runs_dir / "models"), "--cb_cluster", cluster,
               "--split", "test", "--seed", str(seed), "--pretrain_dir", str(p["score"]),
               "--pretrain_ckpt", "best_ema_inference_epoch_model",
               "--filtering_model_dir", str(p["confidence"]),
               "--filtering_ckpt", "best_model.pt", "--moad_dir", str(p["data"]),
               "--moad_esm_embeddings_path", str(p["moad_esm"]),
               "--moad_esm_embeddings_sequences_path", str(p["sequences"]),
               "--cache_path", str(args.runs_dir / "cache"),
               "--sampling_alpha", "1", "--sampling_beta", "1", "--cudnn_benchmark",
               "--use_ema", "--n_epochs", "300", "--cb_inference_freq", "5",
               "--batch_size", "5", "--fixed_length", "100", "--keep_original_train",
               "--total_trainset_size", "100", "--num_inference_complexes", "100",
               "--inference_samples", "8", "--initial_iterations", "10",
               "--inference_iterations", "4", "--inference_batch_size", "4",
               "--confidence_cutoff", "-4", "--max_complexes_per_couple", "20",
               "--minimum_t", "0", "--buffer_sampling_alpha", "2",
               "--buffer_sampling_beta", "1", "--save_model_freq", "25",
               "--save_final_rmsds"]
    if args.pdbbind_dir is not None:
        command += ["--pdbbind_dir", str(args.pdbbind_dir)]
    if args.pdbbind_esm is not None:
        command += ["--pdbbind_esm_embeddings_path", str(args.pdbbind_esm)]
    if args.pdbbind_sequences is not None:
        command += ["--pdbbind_esm_embeddings_sequences_path", str(args.pdbbind_sequences)]
    return command


def replay_preflight(args, official):
    root = args.pdbbind_dir or paths(official)["data"]
    needed = [root / "pdb_superligand", root / "pdb_protein"]
    missing = [str(path) for path in needed if not path.is_dir()]
    if args.pdbbind_esm and not args.pdbbind_esm.is_file():
        missing.append(str(args.pdbbind_esm))
    if args.pdbbind_sequences and not args.pdbbind_sequences.is_file():
        missing.append(str(args.pdbbind_sequences))
    if args.pdbbind_dir and (args.pdbbind_esm is None or args.pdbbind_sequences is None):
        missing.append("Separate PDBBind data requires --pdbbind-esm and --pdbbind-sequences")
    if missing:
        raise RuntimeError("PDBBind replay inputs missing:\n" + "\n".join(missing))


def execute_or_show(command, official, log_path, expected, execute):
    print("$ " + shlex.join(str(part) for part in command))
    if not execute:
        return
    if expected.exists():
        print("Already complete; skipping:", expected)
        return
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with log_path.open("w", encoding="utf-8") as log:
        result = subprocess.run(command, cwd=official, stdout=log, stderr=subprocess.STDOUT,
                                check=False)
    if result.returncode:
        raise RuntimeError(f"Experiment failed (exit {result.returncode}); see {log_path}")
    if not expected.is_file():
        raise RuntimeError(f"Process exited successfully but expected output is missing: {expected}")
    print("Completed:", expected)


def score_directory(out_dir, expected_names, samples):
    np = dependencies()
    log_path = out_dir / "run.log"
    if log_path.is_file():
        with log_path.open(encoding="utf-8", errors="replace") as handle:
            if any("Using non corrected RMSD" in line for line in handle):
                raise ValueError(f"Symmetry-corrected RMSD failed for at least one pose in {log_path}")
    names = [str(v) for v in np.load(out_dir / "complex_names.npy", allow_pickle=False).tolist()]
    rmsds = np.load(out_dir / "rmsds.npy", allow_pickle=False)
    confidences = np.load(out_dir / "confidences.npy", allow_pickle=False)
    if len(names) != len(set(names)) or set(names) != set(expected_names):
        raise ValueError(f"Unexpected or missing complex names in {out_dir}")
    if rmsds.shape != (len(names), samples) or confidences.shape != rmsds.shape:
        raise ValueError(f"Unexpected pose array shape in {out_dir}")
    if not np.all(np.isfinite(rmsds)) or not np.all(np.isfinite(confidences)):
        raise ValueError(f"Non-finite RMSD or confidence in {out_dir}")
    top = rmsds[np.arange(len(names)), np.argmax(confidences, axis=1)]
    return {name: float(value) for name, value in zip(names, top)}


def summarize(manifest, runs_dir, seeds, samples, repeats):
    rows = []
    for seed in seeds:
        base = [score_directory(runs_dir / "baseline" /
                                f"clusters85_poses{samples}_seed{seed}_rep{repeat}",
                                manifest["subset"], samples)
                for repeat in range(1, repeats + 1)]
        for index, (cluster, names) in enumerate(manifest["groups"].items(), 1):
            model_name = f"cluster{index:02d}_{slug(cluster)}_seed{seed}"
            after = [score_directory(runs_dir / "evaluation" /
                                     f"cluster{index:02d}_{slug(cluster)}_poses{samples}_seed{seed}_rep{repeat}",
                                     names, samples)
                     for repeat in range(1, repeats + 1)]
            metrics_path = runs_dir / "models" / model_name / "training_metrics.pkl"
            with metrics_path.open("rb") as handle:
                metrics = pickle.load(handle)
            steps = metrics.get("train_optimizer_steps")
            if steps is None or len(steps) != 300 or any(sum(steps[i:i + 5]) != 200 for i in range(0, 300, 5)):
                raise ValueError(f"Optimizer steps do not match 60 x 200 paper schedule: {metrics_path}")
            before_hits = sum(trial[name] < 2.0 for trial in base for name in names)
            after_hits = sum(trial[name] < 2.0 for trial in after for name in names)
            rows.append({"cluster": cluster, "seed": seed, "n": len(names),
                         "eval_repeats": repeats, "optimizer_steps": sum(steps),
                         "baseline_hits": before_hits, "trained_hits": after_hits,
                         "baseline_percent": 100 * before_hits / (len(names) * repeats),
                         "trained_percent": 100 * after_hits / (len(names) * repeats)})
    out = runs_dir / "summary"
    out.mkdir(parents=True, exist_ok=True)
    with (out / "per_cluster.csv").open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    baseline_hits = sum(row["baseline_hits"] for row in rows)
    trained_hits = sum(row["trained_hits"] for row in rows)
    denominator = 85 * len(seeds) * repeats
    result = {"source": "actual official inference output", "seeds": list(seeds),
              "n_per_seed": 85, "candidate_poses": samples, "eval_repeats": repeats,
              "metric": "confidence Top-1 symmetry-corrected heavy-atom RMSD < 2 A",
              "baseline_hits": baseline_hits, "trained_hits": trained_hits,
              "denominator": denominator,
              "baseline_percent": 100 * baseline_hits / denominator,
              "trained_percent": 100 * trained_hits / denominator}
    (out / "results.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
    print(json.dumps(result, indent=2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("phase", choices=("status", "baseline", "train", "evaluate", "summarize", "checkpoint"))
    parser.add_argument("--official", type=Path, default=OFFICIAL)
    parser.add_argument("--runs-dir", type=Path, default=DEFAULT_RUNS)
    parser.add_argument("--cluster", default="all", help="Cluster name, 1-8 index, or all")
    parser.add_argument("--seeds", nargs="+", type=int, default=list(SEEDS))
    parser.add_argument("--set", choices=("clusters", "full"), default="clusters")
    parser.add_argument("--samples", type=int, choices=(8, 10), default=8)
    parser.add_argument("--eval-repeats", type=int, default=4,
                        help="Independent 8-pose passes; paper protocol uses 4")
    parser.add_argument("--pdbbind-dir", type=Path)
    parser.add_argument("--pdbbind-esm", type=Path)
    parser.add_argument("--pdbbind-sequences", type=Path)
    parser.add_argument("--model-dir", type=Path, help="Score-model directory for checkpoint comparison")
    parser.add_argument("--ckpt", default="best_model.pt", help="Checkpoint file inside --model-dir")
    parser.add_argument("--label", help="Short output label for checkpoint comparison")
    parser.add_argument("--execute", action="store_true", help="Actually launch expensive GPU jobs")
    args = parser.parse_args()
    args.official = args.official.resolve()
    args.runs_dir = args.runs_dir.resolve()
    if len(args.seeds) != len(set(args.seeds)):
        parser.error("Seeds must be distinct.")
    if args.eval_repeats < 1 or args.eval_repeats > 100:
        parser.error("--eval-repeats must be between 1 and 100")
    if args.phase == "status":
        p = paths(args.official)
        for key, path in p.items():
            print(f"{key:16} {'present' if path.exists() else 'MISSING'}  {path}")
        manifest, missing = dataset_manifest(args.official, strict=False)
        if manifest is not None:
            print("189 full complexes; 85 cluster complexes; eight clusters:")
            for i, (name, members) in enumerate(manifest["groups"].items(), 1):
                print(f"  {i}: {name} ({len(members)})")
        return 0 if not missing else 2

    if args.execute and args.phase != "summarize":
        try:
            import torch
        except ImportError as exc:
            raise RuntimeError("GPU execution requires the project's PyTorch environment.") from exc
        if not torch.cuda.is_available():
            raise RuntimeError("No CUDA GPU is available; run this phase on the AutoDL instance.")

    manifest, _ = dataset_manifest(args.official)
    files = name_files(manifest, args.runs_dir)
    p = paths(args.official)
    if args.phase == "summarize":
        summarize(manifest, args.runs_dir, args.seeds, args.samples, args.eval_repeats)
        return 0
    if args.phase == "baseline":
        selected = "full189.npy" if args.set == "full" else "clusters85.npy"
        names = args.runs_dir / "manifests" / selected
        for seed in args.seeds:
            for repeat in range(1, args.eval_repeats + 1):
                out = (args.runs_dir / "baseline" /
                       f"{args.set}{189 if args.set == 'full' else 85}_poses{args.samples}_seed{seed}_rep{repeat}")
                command = inference_command(args.official, p["score"],
                                            "best_ema_inference_epoch_model.pt", names, out,
                                            evaluation_seed(seed, repeat), p["moad_esm"],
                                            p["sequences"], args.samples)
                execute_or_show(command, args.official, out / "run.log", out / "complex_names.npy", args.execute)
        return 0

    if args.phase == "checkpoint":
        if args.model_dir is None or args.label is None:
            parser.error("checkpoint requires --model-dir and --label")
        model_dir = args.model_dir.resolve()
        if not (model_dir / "model_parameters.yml").is_file() or not (model_dir / args.ckpt).is_file():
            raise RuntimeError("Model YAML or checkpoint file is missing in " + str(model_dir))
        selected = "full189.npy" if args.set == "full" else "clusters85.npy"
        names_path = args.runs_dir / "manifests" / selected
        expected_names = manifest["full"] if args.set == "full" else manifest["subset"]
        scored = []
        for seed in args.seeds:
            for repeat in range(1, args.eval_repeats + 1):
                out = (args.runs_dir / "checkpoints" /
                       f"{slug(args.label)}_{args.set}{len(expected_names)}_poses{args.samples}_seed{seed}_rep{repeat}")
                command = inference_command(args.official, model_dir, args.ckpt, names_path,
                                            out, evaluation_seed(seed, repeat), p["moad_esm"],
                                            p["sequences"], args.samples)
                execute_or_show(command, args.official, out / "run.log", out / "complex_names.npy", args.execute)
                if args.execute:
                    scored.append(score_directory(out, expected_names, args.samples))
        if scored:
            successes = sum(value < 2.0 for trial in scored for value in trial.values())
            total = len(expected_names) * len(scored)
            print(json.dumps({"label": args.label, "set": args.set,
                              "eval_repeats": args.eval_repeats,
                              "successes": successes, "total": total,
                              "top1_percent": 100 * successes / total}, ensure_ascii=False))
        return 0

    chosen = choose_clusters(manifest, args.cluster)
    if args.phase == "train":
        replay_preflight(args, args.official)
    for cluster in chosen:
        index = list(manifest["groups"]).index(cluster) + 1
        for seed in args.seeds:
            run_name = f"cluster{index:02d}_{slug(cluster)}_seed{seed}"
            model = args.runs_dir / "models" / run_name
            if args.phase == "train":
                command = training_command(args.official, cluster, run_name, seed, args)
                execute_or_show(command, args.official, model / "run.log",
                                model / "final_ema_inference_epoch_model.pt", args.execute)
            else:
                ckpt = model / "final_ema_inference_epoch_model.pt"
                if args.execute and not ckpt.is_file():
                    raise RuntimeError(f"Training checkpoint missing: {ckpt}")
                for repeat in range(1, args.eval_repeats + 1):
                    out = (args.runs_dir / "evaluation" /
                           f"cluster{index:02d}_{slug(cluster)}_poses{args.samples}_seed{seed}_rep{repeat}")
                    command = inference_command(args.official, model,
                                                "final_ema_inference_epoch_model.pt", files[cluster],
                                                out, evaluation_seed(seed, repeat), p["moad_esm"],
                                                p["sequences"], args.samples)
                    execute_or_show(command, args.official, out / "run.log", out / "complex_names.npy", args.execute)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (RuntimeError, ValueError, FileNotFoundError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        raise SystemExit(1)
